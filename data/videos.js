/** Strips trailing/leading Arabic punctuation and diacritics so word
 * matching isn't broken by e.g. "بحياتك؟" vs "بحياتك". */
export function normalizeArabicWord(w) {
  return (w || '')
    .replace(/[\u064B-\u0652]/g, '') // diacritics
    .replace(/[؟،.!؛:"'’]/g, '') // punctuation
    .trim()
}

/**
 * Finds every line, across every video, that contains a word matching
 * `word` (normalized). Powers the "see this word in other videos" feature —
 * one line per matching video/context, not every duplicate within a video.
 */
export function findWordExamples(word) {
  const target = normalizeArabicWord(word)
  if (!target) return []

  const results = []
  for (const video of videos) {
    for (const line of video.transcript) {
      const hasMatch = line.words.some((w) => normalizeArabicWord(w.arabic) === target)
      if (hasMatch) {
        results.push({
          videoId: video.id,
          videoTitle: video.title,
          lineArabic: line.arabic,
          lineGloss: line.gloss,
          startSec: line.startSec,
        })
        break // one example per video is enough
      }
    }
  }
  return results
}
